use std::{collections::HashSet, path::Path, time::Duration};

use reqwest::Url;
use serde::{Deserialize, Serialize};
use tokio::task::JoinSet;

use super::{installed_yt_dlp, run_yt_dlp, source_video_url, valid_video_id, YtDlpError};
use crate::library::queries::search_words;

const SEARCH_TIMEOUT: Duration = Duration::from_secs(16);
const DETAILS_TIMEOUT: Duration = Duration::from_secs(7);
const SOURCE_LIMIT: usize = 12;
const DETAILS_CONCURRENCY: usize = 6;
const OUTPUT_LIMIT: u64 = 2 * 1024 * 1024;
const METADATA: &str =
    "%(.{id,title,track,artists,artist,creator,uploader,channel,album,description,duration,thumbnail,thumbnails})j\t%(formats.:.{ext,vcodec})j";

#[derive(Default, Deserialize)]
#[serde(default)]
struct Item {
    id: String,
    title: Option<String>,
    track: Option<String>,
    artists: Option<Vec<String>>,
    artist: Option<String>,
    creator: Option<String>,
    uploader: Option<String>,
    channel: Option<String>,
    album: Option<String>,
    description: Option<String>,
    duration: Option<f64>,
    thumbnail: Option<String>,
    thumbnails: Option<Vec<Thumbnail>>,
    formats: Option<Vec<VideoFormat>>,
}

#[derive(Deserialize)]
struct Thumbnail {
    url: Option<String>,
    width: Option<u32>,
    height: Option<u32>,
}

#[derive(Deserialize)]
struct VideoFormat {
    ext: Option<String>,
    vcodec: Option<String>,
}

#[derive(Serialize)]
pub(crate) struct SearchResult {
    id: String,
    title: String,
    artist: Option<String>,
    duration: Option<f64>,
    thumbnail: Option<String>,
    #[serde(rename = "videoAvailable")]
    video_available: Option<bool>,
    clip_title: bool,
}

fn nonempty(value: Option<&str>) -> Option<&str> {
    value.map(str::trim).filter(|text| !text.is_empty())
}

fn thumbnail_url(text: &str) -> bool {
    Url::parse(text).is_ok_and(|url| {
        url.scheme() == "https"
            && url.host_str().is_some_and(|host| {
                host == "i.ytimg.com"
                    || host.ends_with(".ytimg.com")
                    || host == "lh3.googleusercontent.com"
                    || host.ends_with(".ggpht.com")
            })
    })
}

impl Item {
    fn is_cover_play(&self, clip_title: bool) -> bool {
        let topic = [self.channel.as_deref(), self.uploader.as_deref()]
            .into_iter()
            .flatten()
            .any(|name| {
                let name = name.trim().to_lowercase();
                name.ends_with(" - topic") || name.ends_with(" — тема")
            });
        let audio_label = self.title.as_deref().is_some_and(|title| {
            let title = title.to_lowercase();
            title.contains("(official audio)")
                || title.contains("[official audio]")
                || title.contains("(официальное аудио)")
        });
        topic
            || audio_label
            || (!clip_title
                && (nonempty(self.track.as_deref()).is_some()
                    && nonempty(self.album.as_deref()).is_some()
                    || self.description.as_deref().is_some_and(|description| {
                        let credit = format!("Auto-generated by {}.", super::SOURCE_DISPLAY_NAME);
                        description.lines().any(|line| line.trim() == credit)
                    })))
    }

    fn title(&self) -> Option<&str> {
        nonempty(self.track.as_deref()).or_else(|| nonempty(self.title.as_deref()))
    }

    fn credited_artist(&self) -> Vec<String> {
        self.artists
            .as_deref()
            .into_iter()
            .flatten()
            .map(|artist| artist.trim())
            .filter(|artist| !artist.is_empty())
            .map(str::to_owned)
            .collect()
    }

    fn result(&self) -> Option<SearchResult> {
        let mut artists = self.credited_artist();
        if artists.is_empty() {
            if let Some(credit) =
                nonempty(self.artist.as_deref()).or_else(|| nonempty(self.creator.as_deref()))
            {
                artists.extend(super::music_metadata::split_credits(credit).map(str::to_owned));
            }
        }
        let title = super::music_metadata::normalize(self.title()?, &mut artists);
        let artist = if artists.is_empty() {
            nonempty(self.uploader.as_deref())
                .or_else(|| nonempty(self.channel.as_deref()))
                .map(|channel| {
                    channel
                        .strip_suffix(" - Topic")
                        .unwrap_or(channel)
                        .to_owned()
                })
        } else {
            Some(artists.join(", "))
        };
        let thumbnail = self
            .thumbnail
            .as_deref()
            .filter(|text| thumbnail_url(text))
            .or_else(|| {
                self.thumbnails
                    .as_deref()?
                    .iter()
                    .filter(|image| image.url.as_deref().is_some_and(thumbnail_url))
                    .max_by_key(|image| {
                        u64::from(image.width.unwrap_or(0)) * u64::from(image.height.unwrap_or(0))
                    })
                    .and_then(|image| image.url.as_deref())
            });
        let clip_title = self
            .title
            .as_deref()
            .is_some_and(super::music_metadata::has_clip_label);
        let cover_play = self.is_cover_play(clip_title);
        Some(SearchResult {
            id: self.id.clone(),
            title,
            artist,
            clip_title: clip_title && !cover_play,
            video_available: if cover_play {
                Some(false)
            } else {
                self.formats
                    .as_ref()
                    .filter(|formats| !formats.is_empty())
                    .map(|formats| {
                        formats.iter().any(|format| {
                            format.ext.as_deref() == Some("mp4")
                                && format
                                    .vcodec
                                    .as_deref()
                                    .is_some_and(|codec| codec.starts_with("avc1"))
                        })
                    })
            },
            duration: self
                .duration
                .filter(|duration| duration.is_finite() && *duration > 0.0),
            thumbnail: Some(
                thumbnail
                    .map(str::to_owned)
                    .unwrap_or_else(|| format!("https://i.ytimg.com/vi/{}/hqdefault.jpg", self.id)),
            ),
        })
    }
}

fn music_url(query: &str) -> Result<Url, YtDlpError> {
    let mut url = Url::parse(&format!("https://{}/search", super::MUSIC_HOST))
        .map_err(|_| YtDlpError::RequestFailed)?;
    url.query_pairs_mut().append_pair("q", query);
    url.set_fragment(Some("songs"));
    Ok(url)
}

fn direct_video(query: &str) -> Option<String> {
    let url = Url::parse(query).ok()?;
    if !matches!(url.scheme(), "http" | "https")
        || !url.username().is_empty()
        || url.password().is_some()
    {
        return None;
    }
    let id = match url.host_str()? {
        super::SHORT_HOST => url.path_segments()?.next()?.to_owned(),
        super::SOURCE_HOST | super::WWW_HOST | super::MOBILE_HOST | super::MUSIC_HOST
            if url.path() == "/watch" =>
        {
            url.query_pairs()
                .find(|(key, _)| key == "v")?
                .1
                .into_owned()
        }
        super::SOURCE_HOST | super::WWW_HOST | super::MOBILE_HOST => {
            let mut segments = url.path_segments()?;
            if !matches!(segments.next()?, "shorts" | "live" | "embed") {
                return None;
            }
            segments.next()?.to_owned()
        }
        _ => return None,
    };
    valid_video_id(&id).then_some(id)
}

async fn run_search(
    path: &Path,
    target: &str,
    flat: bool,
    limit: &str,
) -> Result<Vec<Item>, YtDlpError> {
    let args = [
        "--ignore-config",
        "--no-plugin-dirs",
        if flat {
            "--flat-playlist"
        } else {
            "--no-flat-playlist"
        },
        "--skip-download",
        "--ignore-no-formats-error",
        "--no-warnings",
        "--socket-timeout",
        "5",
        "--retries",
        "0",
        "--extractor-retries",
        "0",
        "--playlist-end",
        limit,
        "--print",
        METADATA,
        "--",
        target,
    ];
    let timeout = if flat {
        SEARCH_TIMEOUT
    } else {
        DETAILS_TIMEOUT
    };
    let (status, stdout) = run_yt_dlp(path, &args, timeout, OUTPUT_LIMIT).await?;
    let results = stdout
        .lines()
        .filter_map(|line| {
            let (metadata, formats) = line.split_once('\t')?;
            let mut item = serde_json::from_str::<Item>(metadata).ok()?;
            item.formats = serde_json::from_str(formats).ok();
            Some(item)
        })
        .filter(|item| valid_video_id(&item.id) && item.title().is_some())
        .collect::<Vec<_>>();
    if status.success() || !results.is_empty() {
        Ok(results)
    } else {
        Err(YtDlpError::RequestFailed)
    }
}

fn rank(query: &str, songs: Vec<SearchResult>, videos: Vec<SearchResult>) -> Vec<SearchResult> {
    let query = query.to_lowercase();
    let words = search_words(&query);
    let mut seen = HashSet::new();
    let mut candidates = Vec::new();
    for (result, song) in songs
        .into_iter()
        .take(SOURCE_LIMIT)
        .map(|item| (item, true))
        .chain(videos.into_iter().map(|item| (item, false)))
    {
        let title = result.title.to_lowercase();
        let context = format!(
            "{title} {}",
            result.artist.as_deref().unwrap_or("").to_lowercase()
        );
        let matched = words.iter().filter(|word| context.contains(**word)).count();
        let full = !words.is_empty() && matched == words.len();
        if seen.insert(result.id.clone()) {
            let artist = result.artist.as_deref().unwrap_or("").to_lowercase();
            let exact = title == query
                || format!("{artist} {title}") == query
                || format!("{title} {artist}") == query;
            candidates.push((
                (
                    full && exact,
                    full && exact && result.clip_title,
                    song,
                    full,
                    matched,
                ),
                result,
            ));
        }
    }
    candidates.sort_by_key(|candidate| std::cmp::Reverse(candidate.0));
    let mut video_count = 0;
    candidates
        .into_iter()
        .filter_map(|((_, _, song, ..), result)| {
            if song {
                return Some(result);
            }
            video_count += 1;
            (video_count <= SOURCE_LIMIT).then_some(result)
        })
        .collect()
}

#[tauri::command]
pub(crate) async fn search_yt_dlp(
    app: tauri::AppHandle,
    query: String,
) -> Result<Vec<SearchResult>, YtDlpError> {
    let query = query.trim();
    if query.chars().count() < 2 || query.len() > 2048 || query.contains(char::is_control) {
        return Err(YtDlpError::InvalidQuery);
    }
    let path = installed_yt_dlp(&app).await?;
    if let Some(id) = direct_video(query) {
        let url = source_video_url(&id)?;
        let items = run_search(&path.path, &url, false, "1").await?;
        return Ok(items
            .into_iter()
            .filter(|item| item.id == id)
            .filter_map(|item| item.result())
            .collect());
    }

    let music = music_url(query)?;
    let video = format!("ytsearch16:{query}");
    let (songs, videos) = tokio::join!(
        run_search(&path.path, music.as_str(), true, "12"),
        run_search(&path.path, &video, true, "16")
    );
    let (songs, videos) = match (songs, videos) {
        (Ok(songs), Ok(videos)) => (songs, videos),
        (Ok(songs), Err(_)) if !songs.is_empty() => (songs, Vec::new()),
        (Err(_), Ok(videos)) if !videos.is_empty() => (Vec::new(), videos),
        (Err(error), _) | (_, Err(error)) => return Err(error),
    };

    let mut songs = songs.iter().filter_map(Item::result).collect::<Vec<_>>();
    let mut videos = videos.iter().filter_map(Item::result).collect::<Vec<_>>();
    let mut seen = HashSet::new();
    songs.retain(|song| seen.insert(song.id.clone()));
    // Resolve track credits before falling back to the channel of the matching video.
    fill_missing_artists(&path.path, &mut songs).await;
    for song in &mut songs {
        if let Some(video) = videos.iter().find(|video| video.id == song.id) {
            song.artist = song.artist.take().or_else(|| video.artist.clone());
            song.duration = song.duration.or(video.duration);
            song.clip_title |= video.clip_title;
        }
    }
    videos.retain(|video| !seen.contains(&video.id));
    Ok(rank(query, songs, videos))
}

async fn fill_missing_artists(path: &Path, results: &mut [SearchResult]) {
    let mut missing = results
        .iter()
        .enumerate()
        .filter_map(|(index, item)| item.artist.is_none().then(|| (index, item.id.clone())))
        .collect::<Vec<_>>()
        .into_iter();
    let mut jobs = JoinSet::new();
    loop {
        for (index, id) in missing.by_ref().take(DETAILS_CONCURRENCY - jobs.len()) {
            let path = path.to_owned();
            jobs.spawn(async move {
                let url = source_video_url(&id).ok()?;
                let items = run_search(&path, &url, false, "1").await.ok()?;
                let item = items.iter().find(|item| item.id == id)?.result()?;
                Some((index, item))
            });
        }
        let Some(job) = jobs.join_next().await else {
            break;
        };
        if let Ok(Some((index, item))) = job {
            let result = &mut results[index];
            result.artist = item.artist;
            result.title = item.title;
            result.clip_title |= item.clip_title;
            result.video_available = item.video_available;
            result.duration = item.duration.or(result.duration);
            result.thumbnail = item.thumbnail.or_else(|| result.thumbnail.take());
        }
    }
}

pub(super) async fn is_playable_clip(path: &Path, id: &str, url: &str) -> Result<bool, YtDlpError> {
    match run_search(path, url, false, "1").await {
        Ok(items) => Ok(items
            .iter()
            .find(|item| item.id == id)
            .and_then(Item::result)
            .is_some_and(|result| result.video_available == Some(true))),
        Err(YtDlpError::RequestFailed) => Ok(false),
        Err(error) => Err(error),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn cover_uploads_are_audio_even_when_they_have_avc_video() {
        let mut item = Item {
            id: "OC8M1VMdbyc".into(),
            title: Some("101 причина".into()),
            track: Some("101 причина".into()),
            album: Some("101 причина".into()),
            channel: Some("VILLIAN - Topic".into()),
            formats: Some(vec![VideoFormat {
                ext: Some("mp4".into()),
                vcodec: Some("avc1".into()),
            }]),
            ..Item::default()
        };
        assert_eq!(item.result().unwrap().video_available, Some(false));
        item.title = Some("101 причина (official music video) prod by OSA".into());
        item.channel = Some("VILLIAN".into());
        assert_eq!(item.result().unwrap().video_available, Some(true));
    }

    #[test]
    fn music_search_preserves_the_query_and_only_accepts_real_video_links() {
        let url = music_url("Дарую & suanoo #songs").unwrap();
        assert_eq!(url.fragment(), Some("songs"));
        assert_eq!(url.query_pairs().next().unwrap().1, "Дарую & suanoo #songs");
        assert_eq!(
            direct_video(&format!(
                "https://{}/0PgTtkJc5ro?t=2",
                super::super::SHORT_HOST
            ))
            .as_deref(),
            Some("0PgTtkJc5ro")
        );
        assert!(direct_video(&format!(
            "https://{}.invalid/watch?v=0PgTtkJc5ro",
            super::super::SOURCE_HOST
        ))
        .is_none());
    }

    #[test]
    fn retains_flat_results_and_prioritizes_an_exact_clip() {
        let item = |id: &str, title: &str| {
            Item {
                id: id.to_owned(),
                title: Some(title.to_owned()),
                uploader: Some("madk1d".to_owned()),
                formats: Some(Vec::new()),
                ..Item::default()
            }
            .result()
            .unwrap()
        };
        let clip = item("clip", "madk1d - дырки в штанах (music video)");
        assert_eq!(clip.video_available, None);
        let results = rank(
            "дырки в штанах",
            vec![item("song", "дырки в штанах")],
            vec![clip],
        );
        assert_eq!(results[0].id, "clip");
    }

    #[test]
    fn keeps_external_videos_below_music_and_removes_duplicates() {
        let item = |id: &str, title: &str, artist: &str| SearchResult {
            id: id.into(),
            title: title.into(),
            artist: Some(artist.into()),
            duration: None,
            thumbnail: None,
            video_available: None,
            clip_title: false,
        };
        let results = rank(
            "Дарую suanoo",
            vec![
                item("related", "хэйкор", "Suanoo"),
                item("song", "дарую", "Suanoo"),
            ],
            vec![
                item("other", "Дарую", "Канал"),
                item("match", "Дарую Suanoo", "Канал"),
                item("song", "дарую", "Suanoo"),
            ],
        );
        assert_eq!(
            results
                .iter()
                .map(|result| result.id.as_str())
                .collect::<Vec<_>>(),
            ["song", "match", "related", "other"]
        );
    }
}
